"""
Performance Benchmark Suite
Measures latency, throughput, and resource utilization
"""
import asyncio
import time
import statistics
import torch
from typing import List, Dict
import aiohttp
import json

class PerformanceBenchmark:
    def __init__(self, base_url: str = "http://localhost:8000"):
        self.base_url = base_url
        self.results: Dict[str, List[float]] = {}
        
    async def measure_latency(self, image_data: bytes, num_requests: int = 100) -> Dict:
        """Measure single-request latency distribution."""
        latencies = []
        
        async with aiohttp.ClientSession() as session:
            tasks = []
            for _ in range(num_requests):
                task = self._send_request(session, image_data)
                tasks.append(task)
                
            results = await asyncio.gather(*tasks, return_exceptions=True)
            
            for result in results:
                if isinstance(result, float):
                    latencies.append(result)
                    
        return {
            "min_ms": min(latencies),
            "max_ms": max(latencies),
            "mean_ms": statistics.mean(latencies),
            "median_ms": statistics.median(latencies),
            "p95_ms": sorted(latencies)[int(len(latencies) * 0.95)],
            "p99_ms": sorted(latencies)[int(len(latencies) * 0.99)],
            "std_dev_ms": statistics.stdev(latencies) if len(latencies) > 1 else 0,
            "total_requests": len(latencies)
        }
        
    async def measure_throughput(self, image_data: bytes, duration_seconds: int = 30) -> Dict:
        """Measure requests per second over a duration."""
        start_time = time.time()
        request_count = 0
        
        async with aiohttp.ClientSession() as session:
            while time.time() - start_time < duration_seconds:
                tasks = [self._send_request(session, image_data) for _ in range(10)]
                results = await asyncio.gather(*tasks, return_exceptions=True)
                request_count += sum(1 for r in results if not isinstance(r, Exception))
                
        elapsed = time.time() - start_time
        return {
            "total_requests": request_count,
            "duration_seconds": elapsed,
            "requests_per_second": request_count / elapsed,
            "avg_latency_ms": (elapsed / request_count) * 1000 if request_count > 0 else 0
        }
        
    async def _send_request(self, session: aiohttp.ClientSession, image_data: bytes) -> float:
        """Send single prediction request and return latency."""
        start = time.perf_counter()
        try:
            async with session.post(
                f"{self.base_url}/predict",
                data=image_data,
                headers={"Content-Type": "image/jpeg"}
            ) as response:
                await response.json()
        except Exception:
            pass
        return (time.perf_counter() - start) * 1000
        
    async def run_all_benchmarks(self, sample_image_path: str):
        """Run complete benchmark suite."""
        with open(sample_image_path, 'rb') as f:
            image_data = f.read()
            
        print("🚀 Starting Performance Benchmarks...\n")
        
        # Latency test
        print("📊 Measuring latency (100 requests)...")
        latency_results = await self.measure_latency(image_data, num_requests=100)
        print(f"   Mean: {latency_results['mean_ms']:.2f}ms")
        print(f"   P95:  {latency_results['p95_ms']:.2f}ms")
        print(f"   P99:  {latency_results['p99_ms']:.2f}ms\n")
        
        # Throughput test
        print("⚡ Measuring throughput (30 seconds)...")
        throughput_results = await self.measure_throughput(image_data, duration_seconds=30)
        print(f"   Requests/sec: {throughput_results['requests_per_second']:.2f}")
        print(f"   Total requests: {throughput_results['total_requests']}\n")
        
        return {
            "latency": latency_results,
            "throughput": throughput_results
        }

if __name__ == "__main__":
    import sys
    benchmark = PerformanceBenchmark()
    
    image_path = sys.argv[1] if len(sys.argv) > 1 else "data/raw/test/sample.jpg"
    
    results = asyncio.run(benchmark.run_all_benchmarks(image_path))
    
    print("✅ Benchmarks complete!")
    print(json.dumps(results, indent=2))
EOF

