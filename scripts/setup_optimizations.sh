"""
Optimized API Launcher with Performance Enhancements
"""
import os
import sys
import asyncio
import logging
from pathlib import Path

# Add project root to path
sys.path.insert(0, str(Path(__file__).parent.parent))

# Load optimized settings
from src.utils.config import load_config
from src.inference.async_pipeline import AsyncInferencePipeline
from src.caching.enhanced_cache import PredictionCache
from src.optimization.gpu_optimizer import GPUOptimizer
from src.models.model_factory import create_model

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def setup_optimized_environment():
    """Configure environment for maximum performance."""
    
    # Enable TF32 for Ampere GPUs
    if torch.cuda.is_available():
        torch.backends.cuda.matmul.allow_tf32 = True
        torch.backends.cudnn.allow_tf32 = True
        
    # Enable benchmark mode for optimal kernel selection
    torch.backends.cudnn.benchmark = True
    
    # Set memory fragmentation guard
    os.environ['PYTORCH_CUDA_ALLOC_CONF'] = 'max_split_size_mb:512'
    
    logger.info("Optimized environment configured")

async def create_optimized_pipeline(config_path: str = "configs/performance_config.yaml"):
    """Create fully optimized inference pipeline."""
    
    # Load configuration
    config = load_config(config_path)
    
    # Setup environment
    setup_optimized_environment()
    
    # Create model
    model = create_model(
        architecture=config.get('model', {}).get('architecture', 'resnet50'),
        pretrained=True,
        num_classes=config.get('model', {}).get('num_classes', 1000)
    )
    
    # Optimize model
    optimizer = GPUOptimizer()
    if config.get('inference', {}).get('use_amp', False):
        model = optimizer.enable_amp(model)
        
    if config.get('inference', {}).get('compile_model', False):
        model = optimizer.compile_model(model)
    
    # Move to GPU
    device = "cuda" if torch.cuda.is_available() else "cpu"
    model = model.to(device)
    model.eval()
    
    # Create async pipeline
    pipeline = AsyncInferencePipeline(
        model=model,
        device=device,
        batch_size=config.get('inference', {}).get('batch_size', 32),
        max_queue_size=config.get('inference', {}).get('max_queue_size', 100),
        timeout_seconds=config.get('inference', {}).get('timeout_seconds', 5.0),
        enable_profiling=config.get('monitoring', {}).get('enable_profiling', True)
    )
    
    # Initialize cache
    cache = None
    if config.get('inference', {}).get('cache_enabled', False):
        cache = PredictionCache(
            backend=config.get('inference', {}).get('cache_backend', 'memory'),
            ttl=config.get('inference', {}).get('cache_ttl_seconds', 3600),
            max_size=config.get('inference', {}).get('max_cache_size', 10000),
            redis_url=os.getenv('REDIS_URL', 'redis://localhost:6379')
        )
    
    await pipeline.start()
    logger.info("Optimized pipeline started successfully")
    
    return pipeline, cache, config

if __name__ == "__main__":
    import uvicorn
    
    # Start optimized pipeline
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    
    pipeline, cache, config = loop.run_until_complete(create_optimized_pipeline())
    
